export function t(lang: Lang) {
  return translations[lang] || translations.en;
}

export function detectLang(pathname: string): Lang {
  if (pathname.startsWith('/fr')) return 'fr';
  if (pathname.startsWith('/es')) return 'es';
  return 'en';
}
